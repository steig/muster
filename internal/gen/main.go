// Command gen turns herdr's bundled API schema into Go types.
//
// Run it with `go generate ./...` after refreshing internal/herdrapi/schema.json
// from `herdr api schema --json`. Every type herdr can hand us is generated, so
// a field that herdr renames or drops stops being a silently-nil map lookup and
// becomes a compile error instead.
//
// Only the success_response half of the schema is generated. Request params are
// small, hand-written, and validated by herdr on arrival; the read side is where
// drift actually hurts.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

// schemaNode is the subset of draft-2020-12 that herdr's schema actually uses.
type schemaNode struct {
	Ref        string                 `json:"$ref"`
	Type       json.RawMessage        `json:"type"`
	Properties map[string]*schemaNode `json:"properties"`
	Required   []string               `json:"required"`
	Items      *schemaNode            `json:"items"`
	Enum       []string               `json:"enum"`
	Const      string                 `json:"const"`
	Format     string                 `json:"format"`
	AnyOf      []*schemaNode          `json:"anyOf"`
	OneOf      []*schemaNode          `json:"oneOf"`
	// additionalProperties is either a schema (a typed map value) or a bare
	// bool (open/closed object), so it cannot decode straight into a node.
	AdditionalProperties json.RawMessage `json:"additionalProperties"`
}

// mapValue returns the schema for a typed map's values, or nil when the node is
// not a typed map (`additionalProperties: true`, `false`, or absent).
func (n *schemaNode) mapValue() *schemaNode {
	if len(n.AdditionalProperties) == 0 {
		return nil
	}
	var node schemaNode
	if err := json.Unmarshal(n.AdditionalProperties, &node); err != nil {
		return nil
	}
	return &node
}

// UnmarshalJSON tolerates the `true`/`false` shorthand, which JSON Schema
// allows anywhere a schema is expected ("any value" / "no value"). herdr uses it
// for at least one property, and a bare bool is not an object.
func (n *schemaNode) UnmarshalJSON(data []byte) error {
	if bytes.Equal(data, []byte("true")) || bytes.Equal(data, []byte("false")) {
		*n = schemaNode{}
		return nil
	}
	type plain schemaNode // avoid recursing back into this method
	return json.Unmarshal(data, (*plain)(n))
}

// types reports the node's JSON types, normalising the string-or-array form the
// schema uses for nullables (`"string"` vs `["string","null"]`).
func (n *schemaNode) types() []string {
	if len(n.Type) == 0 {
		return nil
	}
	var one string
	if err := json.Unmarshal(n.Type, &one); err == nil {
		return []string{one}
	}
	var many []string
	_ = json.Unmarshal(n.Type, &many)
	return many
}

func (n *schemaNode) nullable() bool {
	for _, t := range n.types() {
		if t == "null" {
			return true
		}
	}
	return false
}

type document struct {
	Protocol int `json:"protocol"`
	Schemas  struct {
		SuccessResponse struct {
			Defs map[string]*schemaNode `json:"$defs"`
		} `json:"success_response"`
	} `json:"schemas"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen <schema.json> <out.go>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fatal(err)
	}
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		fatal(err)
	}
	defs := doc.Schemas.SuccessResponse.Defs
	if len(defs) == 0 {
		fatal(fmt.Errorf("no success_response $defs in %s", os.Args[1]))
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/gen from herdr's API schema. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source: `herdr api schema --json`, protocol %d.\n\n", doc.Protocol)
	fmt.Fprintf(&buf, "package herdrapi\n\n")
	fmt.Fprintf(&buf, "import \"encoding/json\"\n\n")
	fmt.Fprintf(&buf, "// Protocol is the herdr socket protocol version these types were generated\n")
	fmt.Fprintf(&buf, "// from. Compare it against a newer `herdr api schema --json` to see whether\n")
	fmt.Fprintf(&buf, "// regenerating is worthwhile.\n")
	fmt.Fprintf(&buf, "const Protocol = %d\n", doc.Protocol)

	for _, name := range sortedKeys(defs) {
		emit(&buf, name, defs[name])
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		// Write the unformatted source so the syntax error is greppable.
		_ = os.WriteFile(os.Args[2]+".broken", buf.Bytes(), 0o644)
		fatal(fmt.Errorf("format generated source: %w", err))
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		fatal(err)
	}
}

// emit writes one top-level definition: an enum, a tagged union, or a struct.
func emit(buf *bytes.Buffer, name string, node *schemaNode) {
	switch {
	case len(node.Enum) > 0:
		emitEnum(buf, name, node)
	case len(node.OneOf) > 0:
		emitUnion(buf, name, node)
	case node.Properties != nil:
		emitStruct(buf, name, node)
	}
}

func emitEnum(buf *bytes.Buffer, name string, node *schemaNode) {
	fmt.Fprintf(buf, "\ntype %s string\n\nconst (\n", name)
	for _, v := range node.Enum {
		fmt.Fprintf(buf, "\t%s%s %s = %q\n", name, pascal(v), name, v)
	}
	fmt.Fprintf(buf, ")\n")
}

// emitUnion expands a const-tagged oneOf (ResponseResult, EventData) into one
// struct per variant. herdr tags every variant with a `type` const, so the
// caller decodes the envelope, switches on the tag, then decodes the variant.
func emitUnion(buf *bytes.Buffer, name string, node *schemaNode) {
	// The union itself stays raw. Callers read the discriminator off the
	// envelope and then decode into the matching variant struct below.
	fmt.Fprintf(buf, "\n// %s is a tagged union; decode it into the matching variant.\n", name)
	fmt.Fprintf(buf, "type %s = json.RawMessage\n", name)

	suffix := unionSuffix(name)
	for _, variant := range node.OneOf {
		tagNode, ok := variant.Properties["type"]
		if !ok || tagNode.Const == "" {
			// Untagged variants (LayoutNode, PopupSize) have no stable Go
			// shape; callers that need them decode json.RawMessage.
			continue
		}
		tag := tagNode.Const
		typeName := pascal(tag) + suffix
		fmt.Fprintf(buf, "\n// %s is the %q variant of %s.\n", typeName, tag, name)
		emitStructBody(buf, typeName, variant)
		fmt.Fprintf(buf, "\n// Tag%s is the %s discriminator for %s.\nconst Tag%s = %q\n",
			typeName, name, typeName, typeName, tag)
	}
}

// unionSuffix names the variant structs of a tagged union: the ResponseResult
// variants become <Tag>Response, the EventData variants become <Tag>Event.
// "Response" rather than "Result" because several payload $defs are already
// named <Tag>Result (PaneSwapResult and friends) and would collide.
func unionSuffix(union string) string {
	switch union {
	case "ResponseResult":
		return "Response"
	case "EventData":
		return "Event"
	default:
		return union
	}
}

func emitStruct(buf *bytes.Buffer, name string, node *schemaNode) {
	fmt.Fprintf(buf, "\n")
	emitStructBody(buf, name, node)
}

func emitStructBody(buf *bytes.Buffer, name string, node *schemaNode) {
	required := map[string]bool{}
	for _, r := range node.Required {
		required[r] = true
	}
	fmt.Fprintf(buf, "type %s struct {\n", name)
	for _, field := range sortedKeys(node.Properties) {
		prop := node.Properties[field]
		// A const-tagged discriminator is always the same string; keep it as a
		// plain field so round-tripping a decoded value stays faithful.
		fmt.Fprintf(buf, "\t%s %s `json:\"%s%s\"`\n",
			pascal(field), goType(prop, required[field]), field, omitempty(prop, required[field]))
	}
	fmt.Fprintf(buf, "}\n")
}

func omitempty(node *schemaNode, required bool) string {
	if required && !node.nullable() {
		return ""
	}
	return ",omitempty"
}

// goType maps a property schema onto a Go type. Anything optional or explicitly
// nullable becomes a pointer so "absent" and "zero" stay distinguishable —
// open_workspace_id being nil (no workspace) is not the same as "".
func goType(node *schemaNode, required bool) string {
	base, alreadyNilable := baseType(node)
	if alreadyNilable {
		return base
	}
	if !required || node.nullable() {
		return "*" + base
	}
	return base
}

// baseType returns the non-pointer type and whether it is already nil-able
// (slices and maps carry their own absent state).
func baseType(node *schemaNode) (string, bool) {
	if node.Ref != "" {
		return refName(node.Ref), false
	}
	// anyOf is how the schema spells "$ref or null".
	if len(node.AnyOf) > 0 {
		for _, alt := range node.AnyOf {
			if alt.Ref != "" {
				return refName(alt.Ref), false
			}
			if ts := alt.types(); len(ts) > 0 && ts[0] != "null" {
				return scalar(alt), false
			}
		}
		return "any", true
	}
	for _, t := range node.types() {
		switch t {
		case "array":
			if node.Items == nil {
				return "[]any", true
			}
			item, _ := baseType(node.Items)
			return "[]" + item, true
		case "object":
			if v := node.mapValue(); v != nil {
				val, _ := baseType(v)
				return "map[string]" + val, true
			}
			return "map[string]any", true
		case "null":
			continue
		default:
			return scalar(node), false
		}
	}
	return "any", true
}

func scalar(node *schemaNode) string {
	for _, t := range node.types() {
		switch t {
		case "string":
			return "string"
		case "boolean":
			return "bool"
		case "integer":
			if strings.HasPrefix(node.Format, "uint") {
				return "uint64"
			}
			return "int64"
		case "number":
			return "float64"
		}
	}
	return "any"
}

func refName(ref string) string {
	parts := strings.Split(ref, "/")
	return parts[len(parts)-1]
}

// pascal converts a snake_case JSON name into an exported Go identifier,
// keeping the initialisms Go's style guide expects.
func pascal(s string) string {
	var out strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' }) {
		switch part {
		case "id", "ids", "url", "json", "ui", "cwd", "pr":
			out.WriteString(strings.ToUpper(part))
		default:
			out.WriteString(strings.ToUpper(part[:1]))
			out.WriteString(part[1:])
		}
	}
	return out.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
